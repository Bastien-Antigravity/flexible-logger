package helpers

// =============================================================================
// ESSENTIAL PROCESS: Cross-platform log directory resolution and file path discovery.
//
// DATA FLOW:
//   1. Traverses runtime caller stack to locate calling project root.
//   2. Falls back to executable directory or current working directory.
//   3. Ensures creation of 'logs/' directory with standard permissions.
//   4. Returns canonical absolute or relative path to log file.
//
// KEY PARAMETERS:
//   - name: Component or application name determining log filename.
//   - baseDir: Resolved root directory anchor.
// =============================================================================

import (
	"os"
	"path/filepath"
	"runtime"
	"strings"
)

// getCallerDir attempts to find the directory of the original source file (e.g. main.go)
// by traversing the call stack and skipping known library paths.
// This provides an extremely robust anchor for 'go run' where os.Executable is in /tmp/.
func getCallerDir() string {
	for i := 1; i < 25; i++ {
		_, file, _, ok := runtime.Caller(i)
		if !ok {
			break
		}
		// Skip list: stdlib and platform internal libs
		skip := false
		libsToSkip := []string{
			"runtime/", "reflect/", "testing/",
			"distributed-config", "microservice-toolbox", "universal-logger",
			"flexible-logger", "safe-socket", "message-serializers",
			"<autogenerated>",
		}
		for _, lib := range libsToSkip {
			if strings.Contains(file, lib) {
				skip = true
				break
			}
		}

		if !skip && file != "" {
			return filepath.Dir(file)
		}
	}
	return ""
}

// -----------------------------------------------------------------------------

// GetDefaultLogPath returns the default log path using the executable name.
func GetDefaultLogPath() string {
	return GetLogPath("")
}

// -----------------------------------------------------------------------------

func isDockerContainer() bool {
	return os.Getenv("DOCKER_ENV") == "true"
}

func sanitizeServiceSegment(raw string) string {
	cleaned := strings.ReplaceAll(raw, "/", "_")
	return strings.ReplaceAll(cleaned, "\\", "_")
}

func resolveLogDir(name, envLogDir string, isDocker bool, baseDir string) string {
	if envLogDir != "" {
		return envLogDir
	}
	if isDocker && name != "" {
		return filepath.Join("/var/log/fleet", sanitizeServiceSegment(name))
	}
	return filepath.Join(baseDir, "logs")
}

// -----------------------------------------------------------------------------

// GetLogPath returns the log file path based on the provided name.
// If name is empty, it falls back to the executable name.
func GetLogPath(name string) string {
	baseDir := "."
	exePath, err := os.Executable()
	if err == nil {
		exeDir := filepath.Dir(exePath)
		// If not in a temporary go-build directory, use the executable's directory
		if !strings.Contains(exeDir, "go-build") && !strings.Contains(exeDir, "T/go-build") {
			baseDir = exeDir
		} else {
			if callerDir := getCallerDir(); callerDir != "" {
				baseDir = callerDir
			} else if wd, err := os.Getwd(); err == nil {
				baseDir = wd
			}
		}
	} else {
		if callerDir := getCallerDir(); callerDir != "" {
			baseDir = callerDir
		} else if wd, err := os.Getwd(); err == nil {
			baseDir = wd
		}
	}

	effectiveName := name
	if effectiveName == "" {
		if err != nil {
			effectiveName = "application"
		} else {
			exeName := filepath.Base(exePath)
			if ext := filepath.Ext(exeName); ext != "" {
				exeName = strings.TrimSuffix(exeName, ext)
			}
			effectiveName = exeName
		}
	}
	safeName := sanitizeServiceSegment(effectiveName)

	logDir := resolveLogDir(safeName, os.Getenv("LOG_DIR"), isDockerContainer(), baseDir)

	// Ensure log directory exists
	_ = os.MkdirAll(logDir, 0755)

	return filepath.Join(logDir, safeName+".log")
}
